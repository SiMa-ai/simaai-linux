// MAX96716
static struct serdes_parse DSER_CONF[] = {
	// Video Pipes And Routing Configuration
	{ 0x0161, 0x20 },
	// Pipe to Controller Mapping Configuration (Pipe Y)
	{ 0x044B, 0x07 },
	{ 0x044C, 0x00 },
	{ 0x044D, 0x2C },
	{ 0x044E, 0x2C },
	{ 0x044F, 0x00 },
	{ 0x0450, 0x00 },
	{ 0x0451, 0x01 },
	{ 0x0452, 0x01 },
	/*
	 * MIPI_TX45(1) map->DPHY destination. The MAX96714 is single-output
	 * with the master output on PHY1; there is no PHY2. The old value 0x2A
	 * (0b10,10,10) routed every map to PHY2 -> packets went nowhere and the
	 * CSI-TX packet count (0x0342) stayed 0. Route all maps to PHY1: 0x15
	 * (0b01,01,01). Verified live: 0x0342 goes non-zero once this is set.
	 */
	{ 0x046D, 0x15 },
	// Double Mode Configuration
	{ 0x0473, 0x01 },
	{ 0x0160, 0x01 },
	{ 0x0483, 0x00 },
	{ 0x0484, 0x00 },
	/*
	 * PHY standby release. MAX96714 2-lane output uses PHY0 (data lanes) +
	 * PHY1 (clock, master). BOTH must leave standby or the CSI output DPLL
	 * never locks (0x0308 bit5 CSIPLLLOCK stays 0). 0xC4 only released PHY1;
	 * 0xF4 releases PHY0+PHY1. Verified live: PLL locks (0x0308=0x21) only
	 * with 0xF4.
	 */
	{ 0x0332, 0xF4 },
	{ 0x04B3, 0x01 },
	// MIPI D-PHY Configuration (CSI PHY 1)
	{ 0x0330, 0x00 }, // MAX96714: 2x2 (single 2-lane PHY), not 2x4
	// LANE configuration 0xC0 -> 4lane, 0x50 -> 2lane (MAX96714 = 2-lane)
	{ 0x040A, 0x50 },
	{ 0x044A, 0x50 },
	{ 0x0333, 0xE4 }, // maxim MAX96714 lane map
	{ 0x0335, 0x00 },
	{ 0x1D00, 0xF4 },
	{ 0x1D00, 0xF4 },
	/*
	 * CSI-TX output DPLL frequency. The MAX96714 is a SINGLE-output part
	 * whose CSI-2 output uses PHY1 -> DPLL freq register 0x0320. The old
	 * value here (0x0323 = PHY2 DPLL) came from the dual-output MAX96716A
	 * recipe; on the MAX96714 that PHY does not drive the output, so the
	 * real output DPLL stayed at its reset rate and the CSI-2 TX emitted
	 * zero packets even though the video pipe locked (0x011A=0x62). Value
	 * 0x2B taken verbatim from the working MAX96714 register dump.
	 */
	{ 0x0320, 0x2B },
	{ 0x033E, 0x01 },
	/* D-PHY TX timing (t_hs / t_clk) from the working MAX96714 dump */
	{ 0x0440, 0x01 },
	{ 0x0445, 0x71 },
	{ 0x0446, 0x19 },
	{ 0x0447, 0x1C },
	{ 0x0449, 0x01 },
	{ 0x1D00, 0xF5 },
	// CSI Output Enable
	{ 0x0325, 0x80 }, // This will resolve the first frame corruption
	{ 0x0313, 0x02 },
};

